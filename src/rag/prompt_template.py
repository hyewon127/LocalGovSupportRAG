# 이 프로젝트의 평가 목표(분석모델 정의서 2.5): 출처 인용률 95% 이상, Hallucination 비율 5% 이하.
# 두 목표 모두 "LLM이 근거 문서 밖의 내용을 말하지 않고, 말한 내용마다 어느 문서인지 밝히게"
# 만드는 것이 핵심이라, 그 규칙을 시스템 프롬프트에 명시적으로 박아둡니다.
#
# [설계 결정 1] 인용 표기는 context_builder.py가 붙인 [1]~[k] 번호를 그대로 쓰게 합니다.
#   번호를 쓰게 하는 이유: "OO공고에 따르면"처럼 자연어로 출처를 쓰게 하면, 나중에 guardrail.py에서
#   "이 답변이 실제로 어느 근거를 인용했는지"를 기계적으로 확인할 수 없습니다. [숫자] 형식이면
#   정규식 한 줄로 뽑아서 sources와 대조할 수 있습니다 (인용률 측정 WBS 7.3에도 그대로 쓰임).
#
# [설계 결정 2] 근거가 없을 때 할 말을 "정확히 이 문장"으로 고정합니다 (NO_EVIDENCE_MESSAGE).
#   "모르면 모른다고 해"라고만 하면 모델마다 "확인이 어렵습니다", "정보가 없네요" 등 표현이 제각각이라
#   코드에서 "근거 없음 응답인지"를 판단할 수 없습니다. 문장을 고정하면 guardrail.py가 문자열 비교로
#   바로 알아볼 수 있습니다.
#
# [설계 결정 3 - 실데이터에서 발견한 함정] region_name은 "공고 본문의 지역"이 아니라 "크롤러가 수집할 때
#   쓴 해시태그(서울)"입니다. 실제로 context_builder.py를 돌려보니 "2026년 중앙부처 및 지자체
#   창업지원사업 통합 공고"는 region_name=서울인데 본문에는 경기/충북/부산 사업 목록이 섞여 있었습니다.
#   그래서 "서울 사업 알려줘"라고 물으면 LLM이 본문 속 경기도 사업을 서울 사업처럼 답할 위험이 있어서,
#   "본문에 적힌 지역을 기준으로 판단하라"는 규칙을 따로 넣었습니다.

NO_EVIDENCE_MESSAGE = "제공된 공고 자료에서 질문에 해당하는 지원사업을 찾지 못했습니다."

SYSTEM_PROMPT = f"""너는 지자체·중앙부처 지원사업 공고를 안내하는 상담 챗봇이다.
반드시 아래 규칙을 지켜서 답한다.

1. [근거 문서]에 적힌 내용만 사용한다. 사전 지식이나 추측으로 내용을 보태지 않는다.
2. 사실을 말하는 문장마다 끝에 근거 문서 번호를 [1], [2]처럼 붙인다. 여러 문서면 [1][3]처럼 붙인다.
   [근거 문서]에 없는 번호는 절대 쓰지 않는다.
3. 질문자의 상황에 도움이 될 수 있는 사업이 [근거 문서]에 하나라도 있으면, 질문의 표현과 공고 제목이 달라도 그 사업을 안내한다.
   질문과 관련된 사업이 [근거 문서]에 전혀 없을 때만, 다른 말을 붙이지 말고 정확히 다음 문장만 출력한다:
   {NO_EVIDENCE_MESSAGE}
4. 지원대상·접수기간·지원금액은 문서에 적힌 표현 그대로 옮긴다. "명시 없음"이면 명시되어 있지 않다고 말한다.
5. 이 서비스는 서울 소재 기업을 위한 것이다. 한 문서 안에 여러 지역의 사업이 섞여 있을 수 있으므로, 문서 제목이 아니라
   본문에 적힌 지역을 기준으로 판단한다. 사용자가 다른 지역을 직접 묻지 않았다면 서울 또는 전국(지역 제한 없음) 대상 사업만
   안내하고, 경기·울산 등 다른 지역 소재 기업만 신청할 수 있는 사업은 안내하지 않는다.
6. 한국어로, 사업별로 나눠서 간결하게 답한다. 마지막 줄에 "정확한 내용은 원문 공고를 확인하세요."를 붙인다.

[답변 형식] <> 부분은 반드시 근거 문서에 적힌 실제 내용으로 바꿔 쓴다. <>나 자리표시자를 그대로 출력하지 않는다.
**<근거 문서 제목의 사업명>** [<문서 번호>]
- 지원대상: <문서에 적힌 대상> [<문서 번호>]
- 접수기간: <문서에 적힌 기간> [<문서 번호>]
- 지원내용: <문서에 적힌 지원 내용> [<문서 번호>]

정확한 내용은 원문 공고를 확인하세요."""

# [2026-09-29 예시 추가] 로컬 7B 모델(qwen2.5)은 규칙 2를 문장으로만 줬을 때 출처를 "OO 공고에 따르면"처럼 사업명으로
# 밝히고 [번호]를 빠뜨렸습니다(평가셋 답변 25건 중 13건, 인용률 48%). 내용은 근거와 맞았지만(근거에 없는 수치 0건)
# guardrail.py가 번호로 출처를 검사하므로 전부 버려졌습니다. 작은 모델은 규칙 문장보다 "완성된 모양"을 더 잘 따라 해서
# 형식 예시를 붙였습니다. 예시 번호를 [1]이 아니라 [2]로 둔 이유: [1]로 두면 모델이 내용과 상관없이 [1]만 복사하는
# 경향이 있어서, "번호는 실제 문서에 맞춰 바뀐다"는 걸 보여주려고.
#
# [2026-09-29 예시 -> 틀로 변경] 위 예시의 "**OO 지원사업** [2]"를 모델이 실제 사업명으로 바꾸지 않고 그대로 베낀 답변이
# 나왔습니다(평가 26건 중 1건 + 웹 화면 확인 중 1건 - 인용 번호는 있어서 인용률 지표로는 안 잡힘). 그럴듯한 가짜 사업명을
# 예시로 두면 그걸 베껴서 더 나쁘므로(없는 사업을 안내 = hallucination), 무엇을 채워야 하는지 적힌 <> 틀로 바꾸고
# "그대로 출력하지 말라"는 문장을 붙였습니다. 베낀 비율은 answer_eval.py의 placeholder_copy_rate로 따로 셉니다.
#
# [2026-09-29 규칙 3 완화] 공고 제목과 다른 말로 물으면("실시간 방송으로 판매" = 라이브커머스) 정답 공고가 근거에 있어도
# 7B 모델이 "찾지 못했다"고 거절했습니다(어휘 치환 질의 중 정답이 top-5에 있던 24개 중 5개). "도움이 될 사업이 하나라도
# 있으면 안내"를 먼저 두고 거절은 "전혀 없을 때만"으로 좁혔더니, 그 5개 중 2개가 답하게 됐고 반드시 거절해야 할 9개
# (무관 질의 6 + 검색이 정답을 못 찾은 3)는 전부 거절을 유지했습니다.
# 처음에는 규칙에 "라이브커머스", "기업승계" 같은 동의어 예시를 넣었는데, 평가셋 질문에서 가져온 표현이라 시험 답을
# 알려주는 것과 같아서(데이터 누수) 뺐습니다. 이 5개 질의는 규칙을 고르는 데 쓰였으므로 평가 수치 해석 시 참고.
#
# [2026-09-29 규칙 5 강화 - 사용자 제보] "창업 지원"이라고만 물었는데 안산·용인·울산 사업이 줄줄이 나왔습니다. 근거 [1]이
# "중앙부처 및 지자체 창업지원사업 통합 공고"(전국 사업 수백 개를 표로 모은 PDF, region_name은 수집 해시태그라 "서울")라서,
# 지역을 안 물으면 옛 규칙 5("지역을 물었다면...")가 적용되지 않았기 때문. 서비스 범위(서울)를 규칙에 명시했더니 창업 질문 4개
# 기준 타지역 사업 언급이 8건 -> 1건. 근본 해결은 통합 공고를 지역별 사업 단위로 나눠 색인하는 것(README 한계점).


def build_messages(question: str, context_text: str) -> list[dict]:
    """
    입력: question - 사용자 원문 질의
          context_text - context_builder.build_context()의 context_text ([1]~[k] 번호가 붙은 근거 문서)
    출력: chat.completions.create(messages=...)에 그대로 넣을 메시지 리스트

    근거 문서를 system이 아니라 user 메시지 쪽에 넣는 이유: system에는 "항상 같은 규칙"만 두고,
    질문마다 바뀌는 내용(근거 문서/질문)은 user에 둬야 규칙과 데이터가 섞이지 않습니다. 공고문 본문에
    "~하십시오" 같은 문장이 있어도 모델이 그걸 "지시"가 아니라 "자료"로 읽게 하려는 목적도 있습니다.
    """
    user_content = (
        f"[근거 문서]\n{context_text}\n\n"
        f"[질문]\n{question}"
    )
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
